import { readFile, mkdir, writeFile, cp } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { transform } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
export async function buildKWin(destination = path.join(root, "dist/kdetiler")) {
  const engine = await readFile(path.join(root, "engine.js"), "utf8");
  const exports = [...engine.matchAll(/^export function (\w+)/gm)].map((match) => match[1]);
  const adapter = await readFile(path.join(root, "kwin/adapter.js"), "utf8");
  const entry = await readFile(path.join(root, "kwin/entry.js"), "utf8");
  const source = `// Generated by npm run build:kwin. Do not edit.\nvar KDETiler = (() => {\n`
    + `if (!Array.prototype.flatMap) Array.prototype.flatMap = function (fn) { return [].concat.apply([], this.map(fn)); };\n`
    + `const Engine = (() => {\nconst structuredClone = (value) => JSON.parse(JSON.stringify(value));\n`
    + engine.replace(/^export /gm, "") + `\nreturn { ${exports.join(", ")} };\n})();\n`
    + adapter.replace(/^import .*;\n/gm, "").replace(/^export /gm, "") + "\n" + entry
    + "\nreturn KDETiler;\n})();\n";
  const { code: bundle } = await transform(source, {
    target: "es2016", sourcemap: "inline",
  });
  await mkdir(path.join(destination, "contents/code"), { recursive: true });
  await cp(path.join(root, "kwin/contents"), path.join(destination, "contents"), { recursive: true });
  await cp(path.join(root, "kwin/metadata.json"), path.join(destination, "metadata.json"));
  await writeFile(path.join(destination, "contents/code/main.js"), bundle);
  return { directory: destination, script: path.join(destination, "contents/code/main.js"), bundle };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await buildKWin();
  const archive = path.join(root, "dist/kdetiler.kwinscript");
  // Unlink only our generated archive so removed package entries cannot survive an update.
  const { unlink } = await import("node:fs/promises");
  await unlink(archive).catch((error) => { if (error.code !== "ENOENT") throw error; });
  execFileSync("zip", ["-q", "-r", archive, "metadata.json", "contents"], { cwd: result.directory });
  console.log(`Built ${archive}\nNot installed or enabled.`);
}
