import { readFile, mkdir, mkdtemp, writeFile, cp, readdir, rename, rm, utimes, realpath } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import vm from "node:vm";
import { transform } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const settingsFiles = ["SettingsWorker.qml", "SettingsWatcher.qml", "bindings.js"];
// Only these package inputs are copied. Do not bundle local files recursively.
const packageContents = [
  "config/main.xml",
  "ui/config.ui",
  "ui/org.ktiler.Settings.desktop",
];

export async function buildKWin(destination = path.join(root, "dist/ktiler")) {
  const sourceRoot = await realpath(root);
  const publicInput = async (relative) => {
    const file = path.join(sourceRoot, relative);
    if (await realpath(file) !== file) throw new Error(`Refusing a symlink in KWin input: ${relative}`);
    return file;
  };
  const readSource = async (relative) => readFile(await publicInput(relative), "utf8");
  const engine = await readSource("engine.js");
  const exports = [...engine.matchAll(/^export function (\w+)/gm)].map((match) => match[1]);
  const adapter = await readSource("kwin/adapter.js");
  const settingsSources = await Promise.all(settingsFiles.map((name) => readSource(`kwin/contents/code/${name}`)));
  const bindings = settingsSources[settingsFiles.indexOf("bindings.js")];
  // KWin's shared QML engine caches components and JS imports by URL, even
  // after unloading the script. Give changed settings code a fresh URL.
  const settingsId = createHash("sha256").update(JSON.stringify(settingsSources)).digest("hex").slice(0, 16);
  const workerDirectory = `code/settings-${settingsId}`;
  const workerPath = `${workerDirectory}/SettingsWorker.qml`;
  const entry = await readSource("kwin/entry.js");
  const source = `// Generated by npm run build:kwin. Do not edit.\nvar ktiler = (() => {\n`
    + `const settingsWorkerPath = ${JSON.stringify(workerPath)};\n`
    + `if (!Array.prototype.flatMap) Array.prototype.flatMap = function (fn) { return [].concat.apply([], this.map(fn)); };\n`
    + `const Engine = (() => {\nconst structuredClone = (value) => JSON.parse(JSON.stringify(value));\n`
    + engine.replace(/^export /gm, "") + `\nreturn { ${exports.join(", ")} };\n})();\n`
    + adapter.replace(/^import .*;\n/gm, "").replace(/^export /gm, "") + "\n" + bindings + "\n" + entry
    + "\nreturn ktiler;\n})();\n";
  const { code: bundle } = await transform(source, {
    target: "es2016", sourcemap: "inline",
  });
  await mkdir(path.join(destination, "contents/code"), { recursive: true });
  for (const name of packageContents) {
    const file = path.join(destination, "contents", name);
    await mkdir(path.dirname(file), { recursive: true });
    await cp(await publicInput(`kwin/contents/${name}`), file);
  }
  const metadata = JSON.parse(await readSource("kwin/metadata.json"));
  metadata["X-Ktiler-SettingsWorker"] = workerPath;
  await writeFile(path.join(destination, "metadata.json"), JSON.stringify(metadata, null, 2) + "\n");
  const worker = path.join(destination, "contents", workerDirectory);
  await mkdir(worker, { recursive: true });
  await Promise.all(settingsFiles.map((name, i) => writeFile(path.join(worker, name), settingsSources[i])));
  const images = path.join(destination, "contents/images");
  await mkdir(images, { recursive: true });
  for (const name of ["ktiler-icon.png", "ktiler-logo-w-text.png"]) {
    await cp(await publicInput(name), path.join(images, name));
  }
  const uiPath = path.join(destination, "contents/ui/config.ui");
  const ui = await readFile(uiPath, "utf8");
  const wordmark = (await readFile(path.join(images, "ktiler-logo-w-text.png"))).toString("base64");
  if (!ui.includes("@@KTILER_WORDMARK_DATA@@")) throw new Error("Missing wordmark placeholder in config.ui");
  await writeFile(uiPath, ui.replace("@@KTILER_WORDMARK_DATA@@", wordmark));
  await cp(await publicInput("LICENSE.md"), path.join(destination, "LICENSE.md"));
  await writeFile(path.join(destination, "contents/code/main.js"), bundle);
  return { directory: destination, script: path.join(destination, "contents/code/main.js"), worker, bundle };
}

async function packageFiles(directory, relative = "") {
  const files = [];
  for (const entry of await readdir(path.join(directory, relative), { withFileTypes: true })) {
    const file = path.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...await packageFiles(directory, file));
    else if (entry.isFile()) files.push(file);
    else throw new Error(`Unexpected KWin package entry: ${file}`);
  }
  return files;
}

